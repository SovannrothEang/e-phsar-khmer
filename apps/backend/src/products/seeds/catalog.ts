import type { ProductSpecGroup } from '../../db/schema/products.schema';

/**
 * Demo catalogue (2026-11-01): the trusted spec pages (`product_specs`) and the
 * listing variants that link to them. Figures are compiled from public
 * manufacturer spec sheets and GSMArena-style references for the market
 * generations named in each entry; they are demo data, so treat them as
 * approximate rather than authoritative.
 */

/** One sellable variant of a catalogue model (becomes one demo listing). */
export interface Variant {
  color: string;
  price: number;
  condition: 'new' | 'used';
}

export interface CarVariant extends Variant {
  year: number;
  trim: string;
  mileageKm: number;
  taxType: 'Plate Number' | 'Tax Paper';
}

export interface PhoneVariant extends Variant {
  storage: string;
  /** Battery-health blurb for used handsets, e.g. "Battery health 91%". */
  note?: string;
}

interface CatalogBase {
  brandSlug: string;
  brandName: string;
  modelName: string;
  specGroups: ProductSpecGroup[];
}

export interface CarEntry extends CatalogBase {
  bodyType: string;
  engineType: 'Petrol' | 'Diesel' | 'Hybrid' | 'Electric';
  transmission: 'Auto' | 'Manual';
  variants: CarVariant[];
}

export interface PhoneEntry extends CatalogBase {
  variants: PhoneVariant[];
}

const group = (
  title: string,
  rows: Record<string, string | string[]>,
): ProductSpecGroup => ({
  title,
  rows: Object.entries(rows).flatMap(([label, value]) =>
    (Array.isArray(value) ? value : [value]).map((v) => ({ label, value: v })),
  ),
});

interface CarSpec {
  engine: string;
  power: string;
  torque: string;
  gearbox: string;
  drive: string;
  fuel: string;
  consumption?: string;
  length: number;
  width: number;
  height: number;
  wheelbase: number;
  seats: number;
  tank?: string;
  extras?: Record<string, string>;
  generation: string;
}

const carGroups = (s: CarSpec): ProductSpecGroup[] => [
  group('General', {
    Generation: s.generation,
    'Seating capacity': `${s.seats} seats`,
    'Fuel type': s.fuel,
    ...(s.tank ? { 'Fuel tank': s.tank } : {}),
  }),
  group('Engine & Transmission', {
    Engine: s.engine,
    Power: s.power,
    Torque: s.torque,
    Transmission: s.gearbox,
    Drivetrain: s.drive,
    ...(s.consumption ? { 'Fuel consumption': s.consumption } : {}),
  }),
  group('Dimensions', {
    Length: `${s.length} mm`,
    Width: `${s.width} mm`,
    Height: `${s.height} mm`,
    Wheelbase: `${s.wheelbase} mm`,
  }),
  ...(s.extras ? [group('Highlights', s.extras)] : []),
];

