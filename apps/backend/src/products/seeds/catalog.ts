  dimensions: string;
  weight: string;
  build: string[];
  sim: string[];
  ip: string;
  displayType: string;
  size: string;
  resolution: string;
  protection: string;
  os: string;
  chipset: string;
  cpu: string;
  gpu: string;
  cardSlot: string;
  internal: string[];
  mainCamera: string[];
  mainFeatures: string;
  mainVideo: string;
  selfie: string[];
  selfieVideo: string;
  jack: boolean;
  wlan: string;
  bluetooth: string;
  usb: string;
  nfc: string;
  sensors: string[];
  battery: string;
  charging: string[];
